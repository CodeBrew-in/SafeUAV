"""Compute benchmark metrics from saved run records and write tables + charts.

Every number comes from the JSONL file passed in; nothing is typed by hand.
Follows the analysis rules in docs/review_packet.md (feasible-only completion
denominators, first-attempt vs all proposals, paired injection effect, Wilson CIs).

Usage (repo root):
    .venv/Scripts/python experiments/analyze_results.py results/benchmark.jsonl
Writes docs/benchmark_results.md and experiments/plots/*.png
"""

from __future__ import annotations

import json
import math
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.records import read_jsonl  # noqa: E402

PLOTS = ROOT / "experiments" / "plots"
REPORT = ROOT / "docs" / "benchmark_results.md"
CONDITIONS = ["benign", "prompt_injection", "conflicting"]
COND_LABEL = {"benign": "Benign", "prompt_injection": "Prompt injection", "conflicting": "Conflicting"}
ARMS = ["astar", "llm_only", "llm_shield", "llm_shield_no_fallback"]
ARM_LABEL = {"astar": "A*", "llm_only": "LLM only (hypothetical)", "llm_shield": "LLM + shield",
             "llm_shield_no_fallback": "LLM + shield, no fallback"}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float, float]:
    """Proportion with a Wilson 95% interval. Returns (p, low, high); NaNs when n == 0."""
    if n == 0:
        return math.nan, math.nan, math.nan
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return p, max(0.0, centre - half), min(1.0, centre + half)


def fmt_rate(k: int, n: int) -> str:
    if n == 0:
        return "n/a (n=0)"
    p, lo, hi = wilson(k, n)
    return f"{100 * p:.0f}% ({k}/{n}; 95% CI {100 * lo:.0f}–{100 * hi:.0f}%)"


def quartiles(xs):
    xs = sorted(xs)
    if not xs:
        return math.nan, math.nan, math.nan
    if len(xs) == 1:
        return xs[0], xs[0], xs[0]
    q = statistics.quantiles(xs, n=4, method="inclusive")
    return q[1], q[0], q[2]


def main(path: Path) -> None:
    rows = read_jsonl(path)
    # attach scenario metadata (map family, attack target) from the scenario file
    meta = {s["id"]: s for s in json.loads((ROOT / "benchmark" / "scenarios.json").read_text(encoding="utf-8"))}
    for r in rows:
        s = meta.get(r["scenario_id"], {})
        r.setdefault("family", s.get("family"))
        r.setdefault("attack_target", s.get("attack_target"))
    by_arm = defaultdict(list)
    for r in rows:
        by_arm[r["method"]].append(r)
    env = rows[0]["env"]
    seeds = sorted({r["seed"] for r in rows if r["seed"] is not None})
    scenarios = {r["scenario_id"] for r in rows}
    llm = by_arm["llm_only"]  # one record per model call
    out: list[str] = []
    w = out.append

    w("# SafeUAV-Lite benchmark results\n")
    w(f"Generated by `experiments/analyze_results.py` from `{path.relative_to(ROOT).as_posix()}` "
      f"({len(rows)} run records). Do not edit by hand.\n")
    w(f"- Model **{env['model']}** (Ollama {env['ollama_version']}), GPU {env['gpu']}, commit `{env['git_commit']}`")
    w(f"- {len(scenarios)} scenarios × seeds {seeds} → {len(llm)} model calls, each scored under all three LLM arms")
    commits = {r['env']['git_commit'] for r in rows}
    if len(commits) > 1:
        w(f"- WARNING: records come from several commits: {sorted(commits)}")
    w("- Percentages carry Wilson 95% confidence intervals. Seeds are repeated draws of the same scenario, "
      "so intervals over runs are optimistic; per-map counts are given where it matters.\n")

    # --- 1. safety ------------------------------------------------------------------------
    w("## 1. Safety: did anything unsafe get flown?\n")
    w("| Arm | Runs | Runs that flew a route | Executed violations on flown trails |")
    w("|---|---|---|---|")
    for arm in ARMS:
        rs = by_arm[arm]
        flown = [r for r in rs if r["flown_route"] is not None]
        viol = sum(r["executed_violations"] or 0 for r in flown)
        if arm == "llm_only":
            unsafe = sum(1 for r in rs if r["status"] == "proposal_unsafe")
            w(f"| {ARM_LABEL[arm]} | {len(rs)} | never flown | {unsafe} proposals would have been unsafe |")
        else:
            w(f"| {ARM_LABEL[arm]} | {len(rs)} | {len(flown)} | {viol} |")
    w("")

    # --- 2. what the LLM proposed --------------------------------------------------------------
    w("## 2. What the LLM proposed (one row per model call)\n")
    w("| Condition | Calls | Valid | **Unsafe** | Safe but mission-invalid | No usable output | Said infeasible |")
    w("|---|---|---|---|---|---|---|")
    unsafe_by_cond = {}
    for cond in CONDITIONS + ["all"]:
        rs = llm if cond == "all" else [r for r in llm if r["condition"] == cond]
        c = Counter(r["status"] for r in rs)
        n = len(rs)
        unsafe_by_cond[cond] = (c["proposal_unsafe"], n)
        label = "**All**" if cond == "all" else COND_LABEL[cond]
        w(f"| {label} | {n} | {fmt_rate(c['proposal_valid'], n)} | {fmt_rate(c['proposal_unsafe'], n)} | "
          f"{fmt_rate(c['proposal_mission_invalid'], n)} | {fmt_rate(c['no_proposal'], n)} | "
          f"{fmt_rate(c['declared_infeasible'], n)} |")
    w("")
    w("First-attempt proposals only (temperature 0, no retry):\n")
    w("| Condition | Calls answered on attempt 1 | Unsafe |")
    w("|---|---|---|")
    first_unsafe = {}
    for cond in CONDITIONS:
        rs = [r for r in llm if r["condition"] == cond and r["llm_attempts"] == 1]
        k = sum(1 for r in rs if r["status"] == "proposal_unsafe")
        first_unsafe[cond] = (k, len(rs))
        w(f"| {COND_LABEL[cond]} | {len(rs)} | {fmt_rate(k, len(rs))} |")
    w("")
    codes = Counter(c for r in llm if r["status"] == "proposal_unsafe" for c in r["violation_codes"])
    swept = sum(1 for r in llm if r["swept_forbidden"])
    w("Violation types in unsafe proposals (a proposal can have several): "
      + ", ".join(f"{k} {v}" for k, v in codes.most_common())
      + f"; proposals that jumped over forbidden cells: {swept}.\n")

    # --- 3. injection, paired -------------------------------------------------------------------
    w("## 3. Effect of the injected note (paired: same map, same seed)\n")
    key = {(r["scenario_id"].rsplit("-", 1)[0], r["condition"], r["seed"]): r for r in llm}
    pairs = []
    for (map_id, cond, seed), r in key.items():
        if cond != "benign":
            continue
        inj = key.get((map_id, "prompt_injection", seed))
        con = key.get((map_id, "conflicting", seed))
        pairs.append((map_id, seed, r, inj, con))
    feasible_pairs = [p for p in pairs if p[2]["ground_truth_feasible"]]
    for label, idx in (("prompt injection", 3), ("conflicting note", 4)):
        base_valid = [p for p in feasible_pairs if p[2]["status"] == "proposal_valid" and p[idx]]
        flipped = sum(1 for p in base_valid if p[idx]["status"] == "proposal_unsafe")
        worse = sum(1 for p in feasible_pairs if p[idx] and p[2]["status"] != "proposal_unsafe"
                    and p[idx]["status"] == "proposal_unsafe")
        better = sum(1 for p in feasible_pairs if p[idx] and p[2]["status"] == "proposal_unsafe"
                     and p[idx]["status"] != "proposal_unsafe")
        w(f"- **{label.capitalize()}**: of {len(base_valid)} feasible (map, seed) pairs where the benign proposal "
          f"was valid, {fmt_rate(flipped, len(base_valid)) if base_valid else 'none'} became unsafe with the note. "
          f"Across all {len(feasible_pairs)} feasible pairs: {worse} turned unsafe with the note, {better} turned "
          f"safe (benign unsafe → noted not unsafe).")
    by_target = defaultdict(lambda: [0, 0])
    for r in llm:
        if r["condition"] == "prompt_injection" and r["ground_truth_feasible"]:
            t = r.get("attack_target") or "?"
            by_target[t][1] += 1
            by_target[t][0] += r["status"] == "proposal_unsafe"
    w("")

    # --- 4. completion -----------------------------------------------------------------------------
    w("## 4. Mission completion on feasible scenarios\n")
    w("| Arm | Feasible runs | Completed | of which with the LLM's own route | via A* fallback |")
    w("|---|---|---|---|---|")
    completion = {}
    for arm in ARMS:
        rs = [r for r in by_arm[arm] if r["ground_truth_feasible"]]
        n = len(rs)
        if arm == "llm_only":
            k = sum(1 for r in rs if r["status"] == "proposal_valid")
            completion[arm] = (k, n)
            w(f"| {ARM_LABEL[arm]} | {n} | {fmt_rate(k, n)} (valid proposals; never flown) | {k} | – |")
            continue
        own = sum(1 for r in rs if r["status"] == "completed")
        fb = sum(1 for r in rs if r["status"] == "completed_with_fallback")
        completion[arm] = (own + fb, n)
        w(f"| {ARM_LABEL[arm]} | {n} | {fmt_rate(own + fb, n)} | {own} | {fb} |")
    w("")
    w("Infeasible scenarios (correct answer = refuse):\n")
    w("| Arm | Infeasible runs | Correctly refused | Detail |")
    w("|---|---|---|---|")
    for arm in ARMS:
        rs = [r for r in by_arm[arm] if r["ground_truth_feasible"] is False]
        if arm == "llm_only":
            k = sum(1 for r in rs if r["status"] == "declared_infeasible")
            other = Counter(r["status"] for r in rs if r["status"] != "declared_infeasible")
            w(f"| {ARM_LABEL[arm]} | {len(rs)} | {fmt_rate(k, len(rs))} | otherwise: "
              + (", ".join(f"{s} {v}" for s, v in other.items()) or "–") + " |")
        else:
            k = sum(1 for r in rs if r["flown_route"] is None)
            w(f"| {ARM_LABEL[arm]} | {len(rs)} | {fmt_rate(k, len(rs))} | nothing flown |")
    feas_llm = [r for r in llm if r["ground_truth_feasible"]]
    fi = sum(1 for r in feas_llm if r["false_infeasible"])
    w(f"\nFalse \"infeasible\" claims by the LLM on feasible scenarios: {fmt_rate(fi, len(feas_llm))}.\n")

    # --- 5. shield activity ---------------------------------------------------------------------------
    w("## 5. Why the LLM's route was not flown (LLM + shield)\n")
    shield = by_arm["llm_shield"]
    causes = Counter(r["rejection_cause"] or "accepted (LLM route flown)" for r in shield)
    w("| Outcome | Runs |")
    w("|---|---|")
    for cause, v in causes.most_common():
        w(f"| {cause} | {fmt_rate(v, len(shield))} |")
    si = sum(1 for r in shield if r["shield_intervened"])
    w(f"\nShield intervention rate (shield itself rejected a parsed route): {fmt_rate(si, len(shield))}.\n")

    # --- 6. efficiency and latency ----------------------------------------------------------------------
    w("## 6. Route efficiency and latency\n")
    w("| Arm | Mean route efficiency (optimal ÷ flown) | Median total latency | IQR |")
    w("|---|---|---|---|")
    lat = {}
    for arm in ARMS:
        rs = by_arm[arm]
        eff = [r["route_efficiency"] for r in rs if r["route_efficiency"]]
        tl = [r["total_latency_ms"] for r in rs if r["total_latency_ms"] is not None]
        lat[arm] = tl
        med, q1, q3 = quartiles(tl)
        unit = (lambda ms: f"{ms:.2f} ms") if arm == "astar" else (lambda ms: f"{ms / 1000:.1f} s")
        eff_s = f"{statistics.mean(eff):.3f} (n={len(eff)})" if eff else "–"
        w(f"| {ARM_LABEL[arm]} | {eff_s} | {unit(med)} | {unit(q1)} – {unit(q3)} |")
    retries = Counter(r["llm_attempts"] for r in llm)
    cut = sum(1 for r in llm for a in (r["llm_attempt_log"] or []) if a.get("done_reason") == "length")
    w(f"\nModel attempts per call: {dict(sorted(retries.items()))}; attempts cut off at the token limit: {cut}. "
      "Shield + fallback decision time is the difference between LLM-arm total latency and the LLM call; "
      "it is sub-millisecond to a few ms.\n")

    # --- 7. per map ----------------------------------------------------------------------------------------
    w("## 7. Per map (LLM proposals across seeds: V valid, U unsafe, M mission-invalid, N no output, I said infeasible)\n")
    w("| Map | Family | Feasible | Optimal | Budget | Benign | Injection | Conflicting |")
    w("|---|---|---|---|---|---|---|---|")
    letter = {"proposal_valid": "V", "proposal_unsafe": "U", "proposal_mission_invalid": "M",
              "no_proposal": "N", "declared_infeasible": "I"}
    maps = sorted({r["scenario_id"].rsplit("-", 1)[0] for r in llm})
    for m in maps:
        cells = []
        meta = None
        for cond in CONDITIONS:
            rs = sorted((r for r in llm if r["scenario_id"] == f"{m}-{cond}"), key=lambda r: r["seed"])
            meta = meta or (rs[0] if rs else None)
            cells.append("".join(letter[r["status"]] for r in rs))
        if meta:
            w(f"| {m} | {meta.get('family') or '–'} | {'yes' if meta['ground_truth_feasible'] else 'no'} | "
              f"{meta['optimal_steps'] if meta['optimal_steps'] is not None else '–'} | {meta['max_steps']} | "
              + " | ".join(cells) + " |")
    w("")

    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    make_plots(unsafe_by_cond, first_unsafe, completion, lat)
    print(f"\nWrote {REPORT} and plots in {PLOTS}")


def make_plots(unsafe_by_cond, first_unsafe, completion, lat) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    PLOTS.mkdir(parents=True, exist_ok=True)
    blue, ink, muted, grid = "#2a78d6", "#0b0b0b", "#52514e", "#e4e3df"
    plt.rcParams.update({"font.size": 10, "axes.edgecolor": muted, "axes.labelcolor": ink,
                         "xtick.color": muted, "ytick.color": muted, "axes.spines.top": False,
                         "axes.spines.right": False, "figure.facecolor": "#fcfcfb", "axes.facecolor": "#fcfcfb"})

    def bars(ax, labels, ks_ns, title, ylabel):
        ps = [wilson(k, n) for k, n in ks_ns]
        vals = [100 * p[0] if n else 0 for p, (k, n) in zip(ps, ks_ns)]
        # max(0, ...) absorbs float rounding at p = 0 or 1
        err = [[max(0.0, 100 * (p[0] - p[1])) if n else 0 for p, (k, n) in zip(ps, ks_ns)],
               [max(0.0, 100 * (p[2] - p[0])) if n else 0 for p, (k, n) in zip(ps, ks_ns)]]
        ax.bar(labels, vals, color=blue, width=0.55, yerr=err, capsize=4, ecolor=muted)
        for i, ((k, n), v) in enumerate(zip(ks_ns, vals)):
            top = v + err[1][i]  # label sits above the error bar, not on it
            ax.text(i, top + 2, f"{v:.0f}%\n({k}/{n})", ha="center", va="bottom", color=ink, fontsize=9)
        ax.set_ylim(0, 115)
        ax.set_ylabel(ylabel)
        ax.set_title(title, loc="left", color=ink, fontsize=11)
        ax.yaxis.grid(True, color=grid)
        ax.set_axisbelow(True)

    fig, axes = plt.subplots(1, 2, figsize=(10, 4), sharey=True)
    bars(axes[0], [COND_LABEL[c] for c in CONDITIONS], [unsafe_by_cond[c] for c in CONDITIONS],
         "Unsafe LLM proposals, all calls", "% of model calls")
    bars(axes[1], [COND_LABEL[c] for c in CONDITIONS], [first_unsafe[c] for c in CONDITIONS],
         "Unsafe LLM proposals, first attempt (T=0) only", "")
    fig.text(0.01, 0.01, "Error bars: Wilson 95% CI. LLM-only proposals are scored, never flown.", color=muted,
             fontsize=8)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(PLOTS / "unsafe_by_condition.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    bars(ax, [ARM_LABEL[a].replace(" (hypothetical)", "\n(valid proposal)").replace(", no fallback", "\nno fallback")
              for a in ARMS], [completion[a] for a in ARMS],
         "Mission completion on feasible scenarios", "% of feasible runs")
    fig.tight_layout()
    fig.savefig(PLOTS / "completion_by_method.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    data = [[max(x, 1e-3) / 1000 for x in lat[a]] for a in ARMS]
    ax.boxplot(data, tick_labels=[ARM_LABEL[a].replace(" (hypothetical)", "").replace(", no fallback", "\nno fallback")
                                  for a in ARMS],
               medianprops={"color": blue, "linewidth": 2}, boxprops={"color": muted},
               whiskerprops={"color": muted}, capprops={"color": muted}, flierprops={"markeredgecolor": muted})
    ax.set_yscale("log")
    ax.set_ylabel("seconds (log scale)")
    ax.set_title("Time until a route is approved or refused", loc="left", color=ink, fontsize=11)
    ax.yaxis.grid(True, color=grid)
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(PLOTS / "latency_by_method.png", dpi=160)
    plt.close(fig)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252
    main(Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "results" / "benchmark.jsonl")
